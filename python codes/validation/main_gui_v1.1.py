    def _plot_static_3d_surface(self):
        deg, strn, di = self.solver.deg, self.solver.strn, self.solver.di
        deg_grid = np.linspace(deg.min(), deg.max(), 40)
        strn_grid = np.linspace(strn.min(), strn.max(), 40)
        D_mesh, S_mesh = np.meshgrid(deg_grid, strn_grid)
        
        grid_points_scaled = self.solver.scaler.transform(np.column_stack((D_mesh.ravel(), S_mesh.ravel())))
        DI_pred = self.solver.rbf_smooth(grid_points_scaled[:, 0], grid_points_scaled[:, 1]).reshape(D_mesh.shape)
        
        self.ax3d.plot_surface(D_mesh, S_mesh, DI_pred, cmap='Blues_r', alpha=0.75, edgecolor='black', linewidth=0.1, rcount=30, ccount=30)
        self.ax3d.scatter(deg, strn, di, color='black', marker='d', s=10, depthshade=False, label='Empirical Data')
        
        self.ax3d.set_xlabel('Angle (deg)', fontsize=11, fontname="Arial")
        self.ax3d.set_ylabel('Strouhal Number', fontsize=11, fontname="Arial")
        self.ax3d.set_zlabel('Directivity Index (dB)', fontsize=11, fontname="Arial")
        self.ax3d.set_title("RBF Directivity Surface Fitting", fontsize=16, fontweight='bold', fontname="Arial", color=self.text_color)
        
        self.ax3d.view_init(elev=20, azim=-125)
        self.ax3d.set_zlim(di.min() - 5, di.max() + 5)
        
        self.ax3d.set_facecolor(self.bg_color)
        
        for pane in [self.ax3d.xaxis, self.ax3d.yaxis, self.ax3d.zaxis]:
            pane.set_pane_color((0.95, 0.95, 0.95, 1.0))
        self.canvas_3d.draw()

    def _update_data_table(self, f_signal, SPLbp, OASPL):
        self.data_tree.delete(*self.data_tree.get_children())
        
        num_mics = len(OASPL)
        columns = ["Frequency (Hz)"] + [f"Mic {i+1} SPL (dB)" for i in range(num_mics)]
        
        self.data_tree["columns"] = columns
        self.data_tree.column("#0", width=0, stretch=tk.NO) 
        self.data_tree.heading("#0", text="")
        
        for col in columns:
            self.data_tree.column(col, anchor=tk.CENTER, width=120)
            self.data_tree.heading(col, text=col)
            
        rows = []
        for j in range(len(f_signal)):
            row = [f"{f_signal[j]:.2f}"] + [f"{SPLbp[j, i]:.2f}" for i in range(num_mics)]
            self.data_tree.insert("", tk.END, values=row)
            rows.append(row)
            
        oaspl_row = ["OASPL (dB)"] + [f"{OASPL[i]:.2f}" for i in range(num_mics)]
        self.data_tree.insert("", tk.END, values=[""] * len(columns))
        self.data_tree.insert("", tk.END, values=oaspl_row, tags=('bold_row',))
        self.data_tree.tag_configure('bold_row', font=("Arial", 10, "bold"), background="#E9ECEF")
        rows.append([""] * len(columns))
        rows.append(oaspl_row)

        self.latest_df = pd.DataFrame(rows, columns=columns)

    def _export_to_csv(self):
        if self.latest_df is None:
            messagebox.showwarning("No Data", "Please run the simulation first before exporting data.")
            return
            
        file_path = filedialog.asksaveasfilename(
            defaultextension=".csv",
            filetypes=[("CSV Files", "*.csv"), ("All Files", "*.*")],
            title="Save Acoustic Data"
        )
        if file_path:
            try:
                self.latest_df.to_csv(file_path, index=False)
                messagebox.showinfo("Export Successful", f"Data successfully saved to:\n{file_path}")
            except Exception as e:
                messagebox.showerror("Export Failed", f"Could not save file:\n{str(e)}")

    def run_calculation(self):
        try:
            self.run_btn.config(text="CALCULATING...", bg="#f39c12")
            self.root.update()

            active_tab_index = self.notebook.index(self.notebook.select())
            is_deflected = (active_tab_index == 1)

            params = {key: float(var.get()) for key, var in (self.entries_def.items() if is_deflected else self.entries_un.items())}

            f_lower = float(self.entries_freq["Lower Frequency (Hz)"].get())
            n_oct = float(self.entries_freq["Octave Band (n for 1/n)"].get())
            nf = int(float(self.entries_freq["Number of Frequencies"].get()))

            mic_coords = []
            for mic in self.mic_entries:
                try:
                    mic_coords.append([float(mic["x_var"].get()), float(mic["y_var"].get()), float(mic["z_var"].get())])
                except ValueError:
                    raise ValueError("All microphone coordinates must be valid numbers.")
            
            mic_location = np.array(mic_coords)
            num_mics = mic_location.shape[0]

            if is_deflected:
                f_signal, SPLbp, SPLbp_average, OASPL = self.solver.solve_deflected(
                    n_eng=params["Number of Engines"], F=params["Thrust per Engine (N)"],
                    ue=params["Exit Velocity (m/s)"], me=params["Exit Mach Number"],
                    dei=params["Exit Diameter (m)"], eta=params["Efficiency"],
                    mic_location=mic_location, x2=params["Impingement Point (m)"],
                    angle=params["Uplift Angle (deg)"], f_lower=f_lower, n_oct=n_oct, nf=nf
                )
            else:
                f_signal, SPLbp, SPLbp_average, OASPL = self.solver.solve_undeflected(
                    n_eng=params["Number of Engines"], F=params["Thrust per Engine (N)"],
                    ue=params["Exit Velocity (m/s)"], me=params["Exit Mach Number"],
                    dei=params["Exit Diameter (m)"], eta=params["Efficiency"],
                    mic_location=mic_location, f_lower=f_lower, n_oct=n_oct, nf=nf
                )

            self._update_data_table(f_signal, SPLbp, OASPL)

            mics_input = self.mics_plot_var.get().strip().lower()
            if mics_input == "all" or mics_input == "":
                plot_indices = list(range(num_mics))
            else:
                try:
                    parts = [p.strip() for p in mics_input.split(',')]
                    plot_indices = [int(p) - 1 for p in parts if p.isdigit()]
                    plot_indices = [i for i in plot_indices if 0 <= i < num_mics]
                    if not plot_indices: plot_indices = list(range(num_mics))
                except Exception:
                    plot_indices = list(range(num_mics))

            self.ax_spec.clear()
            self.ax_oaspl.clear()
            
            plot_font = self.font_var.get()
            l_style = self.line_var.get()
            l_width = float(self.width_var.get())

            # =========================================================================
            # SPECTRUM: Calculated Data
            # =========================================================================
            self.ax_spec.plot(f_signal, SPLbp_average, label='Calculated Average SPL', 
                              marker='o', markersize=6, 
                              linestyle=l_style, linewidth=l_width, color=self.cherry_red)

            # --- NEW: OVERLAY EXPERIMENTAL CSV DATA ---
            csv_path = self.csv_var.get().strip()
            if csv_path:
                try:
                    exp_df = pd.read_csv(csv_path, header=None)
                    if exp_df.shape[1] >= 2:
                        f_exp = exp_df.iloc[:, 0].to_numpy()
                        spl_exp = exp_df.iloc[:, 1].to_numpy()
                        self.ax_spec.plot(f_exp, spl_exp, label='Experimental (Validation)', 
                                          color='blue', linestyle='--', marker='*', 
                                          markersize=8, linewidth=max(1.5, l_width-0.5))
                except Exception as e:
                    print(f"Warning: Could not load CSV data for overlay. {e}")
            # ------------------------------------------

            self.ax_spec.set_xscale('log')
            self.ax_spec.set_xlim(np.min(f_signal) * 0.8, np.max(f_signal) * 1.2)
            self.ax_spec.minorticks_on()
            self.ax_spec.tick_params(axis='both', which='major', labelsize=10, width=1.5, length=6, direction='in', top=True, right=True)
            self.ax_spec.grid(which='major', linestyle='-', linewidth='0.5', color='black', alpha=0.4)
            self.ax_spec.grid(which='minor', linestyle=':', linewidth='0.5', color='gray', alpha=0.2)
            
            self.ax_spec.set_xlabel('Frequency (Hz)', fontsize=12, fontname=plot_font, color=self.text_color)
            self.ax_spec.set_ylabel('SPL (dB)', fontsize=12, fontname=plot_font, color=self.text_color)
            self.ax_spec.set_title("Deflected Jet Spectrum" if is_deflected else "Undeflected Jet Spectrum", fontsize=14, fontweight='bold', fontname=plot_font, color=self.text_color)
            self.ax_spec.legend(loc='best', frameon=True, prop={'family': plot_font, 'size': 10})

            # =========================================================================
            # OASPL: Still plots individual microphones based on selection
            # =========================================================================
            selected_mic_labels = [f"Mic {i+1}" for i in plot_indices]
            selected_oaspl = [OASPL[i] for i in plot_indices]
            
            self.ax_oaspl.plot(selected_mic_labels, selected_oaspl, marker='D', color=self.btn_color, linestyle='-.', linewidth=l_width, markersize=8)
            
            self.ax_oaspl.set_xlabel('Microphone Array Element', fontsize=12, fontname=plot_font, color=self.text_color)
            self.ax_oaspl.set_ylabel('OASPL (dB)', fontsize=12, fontname=plot_font, color=self.text_color)
            self.ax_oaspl.set_title('Overall Sound Pressure Level (OASPL)', fontsize=14, fontweight='bold', fontname=plot_font, color=self.text_color)
            self.ax_oaspl.grid(True, linestyle='-', linewidth='0.5', color='black', alpha=0.4)

            for ax in [self.ax_spec, self.ax_oaspl]:
                for label in ax.get_xticklabels() + ax.get_yticklabels():
                    label.set_fontname(plot_font)

            self.cursor_spec = Cursor(self.ax_spec, useblit=True, color='red', linewidth=1, linestyle='--')
            self.cursor_oaspl = Cursor(self.ax_oaspl, useblit=True, color='red', linewidth=1, linestyle='--')

            self.canvas_spec.draw()
            self.canvas_oaspl.draw()
            
            self.run_btn.config(text="▶ RUN SIMULATION", bg=self.btn_color)
            self.viz_notebook.select(self.vtab_spec)

        except Exception as e:
            self.run_btn.config(text="▶ RUN SIMULATION", bg=self.btn_color)
            messagebox.showerror("Simulation Error", f"An error occurred during calculation:\n{str(e)}")

