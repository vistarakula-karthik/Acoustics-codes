    def _create_form(self, parent_frame, param_list, dict_ref):
        for i, (label_text, default_val) in enumerate(param_list):
            ttk.Label(parent_frame, text=label_text).grid(row=i, column=0, sticky="w", pady=4)
            entry_var = tk.StringVar(value=default_val)
            entry = ttk.Entry(parent_frame, textvariable=entry_var, justify="right", width=12)
            entry.grid(row=i, column=1, sticky="e", padx=5, pady=4)
            dict_ref[label_text] = entry_var

    def _add_mic_row(self, x_val, y_val, z_val):
        row_idx = len(self.mic_entries) + 1 
        lbl = ttk.Label(self.mic_inner_frame, text=f"#{row_idx}", width=5)
        lbl.grid(row=row_idx, column=0, padx=2, pady=2)
        
        x_var, y_var, z_var = tk.StringVar(value=str(x_val)), tk.StringVar(value=str(y_val)), tk.StringVar(value=str(z_val))
        
        x_ent = ttk.Entry(self.mic_inner_frame, textvariable=x_var, width=8, justify="center")
        x_ent.grid(row=row_idx, column=1, padx=2, pady=2)
        y_ent = ttk.Entry(self.mic_inner_frame, textvariable=y_var, width=8, justify="center")
        y_ent.grid(row=row_idx, column=2, padx=2, pady=2)
        z_ent = ttk.Entry(self.mic_inner_frame, textvariable=z_var, width=8, justify="center")
        z_ent.grid(row=row_idx, column=3, padx=2, pady=2)
        
        self.mic_entries.append({
            "label": lbl, "x_ent": x_ent, "y_ent": y_ent, "z_ent": z_ent,
            "x_var": x_var, "y_var": y_var, "z_var": z_var
        })
        self.mic_canvas.update_idletasks()
        self.mic_canvas.yview_moveto(1.0)

    def _remove_mic_row(self):
        if len(self.mic_entries) > 1: 
            last_mic = self.mic_entries.pop()
            for key in ["label", "x_ent", "y_ent", "z_ent"]:
                last_mic[key].destroy()

